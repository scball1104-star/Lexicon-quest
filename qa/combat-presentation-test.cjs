'use strict';
const assert=require('node:assert/strict');
const L=require('../rpg-engine.js');
const V=require('../rpg-combat-ui.js');
let checks=0;
const check=(condition,message)=>{assert.ok(condition,message);checks++;};
for(let region=0;region<8;region++){
  const g=new L.Game();g.startBattle({id:'presentation-'+region,r:region,type:'boss'});
  const b=g.battle;const before=JSON.stringify({s:g.s,b});
  const initial=V.suggest(g,'attack',0);
  check(!!initial.label&&!!initial.text,'region '+region+' has battle briefing');
  check(V.timeline(g).length===4,'region '+region+' has 3-ally turn order and enemy phase');
  check(V.timeline(g)[0].active,'region '+region+' highlights first active actor');
  check(V.enemyIntel(g,b,b.enemies[0],0).weak===b.enemies[0].weak,'region '+region+' weakness visible');
  check(V.enemyIntel(g,b,b.enemies[0],0).percent===100,'region '+region+' HP starts full');
  check(V.actionPreview(g,'attack',0).includes('Focus'),'region '+region+' action preview explains Focus');
  check(V.actionPreview(g,'guard',0).includes('Guard'),'region '+region+' defense preview');
  check(V.actionPreview(g,'potion',0).includes('65 HP'),'region '+region+' potion preview');
  check(V.actionPreview(g,'ether',0).includes('18 MP'),'region '+region+' ether preview');
  check(before===JSON.stringify({s:g.s,b}),'region '+region+' rendering helpers never mutate the game');
  b.enemies[0].charge=true;
  check(V.suggest(g,'attack',0).level==='danger','region '+region+' charged guardian triggers danger');
  check(V.intentKind(g.intent(b.enemies[0]))==='danger','region '+region+' charged intent color');
  b.enemies[0].charge=false;
  b.enemies[0].weak='ice';b.enemies[0].resist='fire';
  check(V.suggest(g,'frost',0).label==='Exploit weakness','region '+region+' elemental advice');
  check(V.suggest(g,'flare',0).label==='Target resists fire','region '+region+' resistance advice');
  b.focus=100;
  check(V.suggest(g,'attack',0).label==='Triad Resonance ready','region '+region+' resonance readiness');
  b.focus=0;
  const snap=V.snapshot(g),oldHP=b.enemies[0].hp;
  const ok=g.act('attack',0);
  check(ok===true,'region '+region+' basic combat still executes');
  check(b.enemies[0].hp<oldHP,'region '+region+' combat retains damage');
  const changes=V.summary(snap,g,'attack');
  check(changes.lines.some(row=>row.type==='damage'),'region '+region+' reports damage');
  check(changes.lines.some(row=>row.type==='focus'),'region '+region+' reports Focus change');
  check(changes.round===b.round,'region '+region+' result knows current round');
  check(V.timeline(g)[1].active,'region '+region+' advances to second character');
}
const g=new L.Game();g.startBattle({id:'ward-test',r:5,type:'boss'});
g.battle.skyShield=true;g.battle.enemies.push({name:'Copy',hp:20,maxhp:20,weak:'fire',resist:'ice'});
check(V.shielded(g.battle),'active guardian ward recognized');
check(V.suggest(g,'attack',0).label==='Break the protection','guardian ward advice prioritizes summoned ally');
check(V.enemyIntel(g,g.battle,g.battle.enemies[1],1).name==='Copy','summon name recognized');
check(V.actionPreview(g,'frost',1).includes('Choose an available action'),'unavailable action does not invent ability');
const partyBefore=V.snapshot(g);g.s.party[0].hp-=10;g.battle.enemies[0].hp-=12;
const diff=V.summary(partyBefore,g,'attack');
check(diff.lines.some(x=>x.text.includes('−12 HP')),'enemy damage difference recognized');
check(diff.lines.some(x=>x.text.includes('−10 HP')),'ally damage difference recognized');
check(V.intentKind('Restore wounded ally')==='support','healing telegraph classified');
check(V.intentKind('Erasure Ward - destroy two rejected truths')==='shield','boss ward telegraph classified');
check(V.intentKind('Standard strike')==='basic','standard attacks neutral');
check(V.actionPreview(g,'resonance',0).includes('Choose an available action'),'unavailable resonance not advertised');
g.battle.focus=100;check(V.actionPreview(g,'resonance',0).includes('ALL living enemies'),'resonance all-target explained');
check(!V.shielded(null),'null battle safely unshielded');
check(V.intentKind('Charging a heavy attack')==='danger','charging telegraph prioritized');
check(L.validSave(g.s),'presentation remains compatible with v3 save');
console.log('PASS '+checks+' tactical presentation checks across all 8 regions, boss defenses, Focus, turn order, preview, damage and saves.');
