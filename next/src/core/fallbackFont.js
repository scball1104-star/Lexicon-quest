/**
 * Build the fallback font: { def, bitmap } where def follows the COMMON.md font format
 * (glyph rects into a generated sheet) and bitmap is { width, height, data: Uint8Array (1 = ink) }.
 */
export function buildFallbackFont() {
  const SHEET_W = 128;
  const CELL_H = 9;
  const glyphs = {};
  const placed = [];
  let x = 0, y = 0;
  for (const ch of Object.keys(G)) {
    const rows = G[ch].split('/');
    const w = Math.max(...rows.map((r) => r.length));
    if (x + w > SHEET_W) { x = 0; y += CELL_H + 1; }
    placed.push({ ch, rows, x, y, w });
    // [x, y, w, h, xoff, yoff, advance]
    glyphs[ch] = [x, y, w, CELL_H, 0, 1, w + 1];
    x += w + 1;
  }
  const height = y + CELL_H;
  const data = new Uint8Array(SHEET_W * height);
  for (const p of placed) {
    p.rows.forEach((row, ry) => {
      for (let rx = 0; rx < row.length; rx++) if (row[rx] === '#') data[(p.y + ry) * SHEET_W + p.x + rx] = 1;
    });
  }
  const def = {
    image: null, lineHeight: 11, baseline: 8, spaceAdvance: 3, glyphs,
    kerning: { LT: -1, TA: -1, AT: -1, Ty: -1, Te: -1, To: -1, Ta: -1, 'r.': -1, 'r,': -1, 'P.': -1, 'P,': -1, 'F.': -1, 'F,': -1 },
    missing: '�',
    fallback: true,
  };
  return { def, bitmap: { width: SHEET_W, height, data } };
}
