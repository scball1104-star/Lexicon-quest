"""Writes next/assets/sprites/README.md from the generated atlases (ids stay in sync with the build)."""
import os, json
from pix import DST


def load(n):
    with open(os.path.join(DST, n + '.json'), encoding='utf-8') as f:
        return json.load(f)


def ids_line(ids, per=6):
    ids = list(ids)
    rows = []
    for i in range(0, len(ids), per):
        rows.append(', '.join('`%s`' % x for x in ids[i:i + per]))
    return '\n'.join('  ' + r for r in rows)


def write(extras):
    pf, pb, npcs, props = load('party_field'), load('party_battle'), load('npcs'), load('props')
    eb, ef, bb, po, mi = load('enemies_battle'), load('enemies_field'), load('bosses_battle'), load('portraits'), load('misc')
    npc_ids = [k for k in npcs['sprites'] if k.startswith('npc_')]
    animal_ids = [k for k in npcs['sprites'] if k.startswith('animal_')]
    L = []
    A = L.append
    A('# Sprites (Lexicon Quest NEXT)')
    A('')
    A('Generated by `next/tools/art/sprites/build_all.py` (deterministic, about 10 seconds). Do not hand-edit the PNGs:')
    A('change the generator (hand-pixeled grids live in `tools/art/sprites/chars/*.py`) and rebuild. Colours come from')
    A('`next/assets/palette.json` at build time (legends use `ramp:index` refs), so a palette tweak only needs a rebuild.')
    A('Contact sheets at 4x and mock screens are written to `tools/art/sprites/out/`.')
    A('')
    A('All atlases follow DESIGN 4: `{"image", "frames": {name: [x,y,w,h]}, "anims": {name: {frames, fps, loop}}}`')
    A('plus the extra keys noted below. Draw with nearest-neighbour at integer positions.')
    A('')
    A('## party_field.png / .json  (24x32 cells, origin [12,31] = feet)')
    A('Per character a 4-row block: rows `down, left, right, up`; columns `stand, stepA, stepB, blink`.')
    A('Frame names `<id>_<dir>_<0|1|2|blink>`; anims `<id>_walk_<dir>` (A, stand, B, stand at 8 fps) and')
    A('`<id>_idle_<dir>` (stand with an occasional blink). Ids: `hero`, `mira`, `bram`. Right = mirrored left.')
    A('')
    A('## party_battle.png / .json  (32x40 cells, facing LEFT, origin [%d,%d] = feet)' % tuple(pb['origin']))
    A('Weapons per character: ' + '; '.join('%s: %s' % (k, ', '.join(v)) for k, v in pb['weapons'].items()) + '.')
    A('Frames: `<id>_<weapon>_{idle_0,idle_1,ready,windup,strike,victory}` for each of its weapons, and')
    A('`<id>_{cast,hurt,defend,kneel,ko}` (kneel = low HP). Anims `<id>_<weapon>_idle` (2-frame breathe) and')
    A('`<id>_<weapon>_attack` (ready, windup, strike). Weapon arcs, flashes and numbers are code/fx.')
    A('')
    A('## npcs.png / .json  (24x32 humanoids, 16x16 animals)')
    A('Humanoids use the same block layout as the party (dirs x stand/stepA/stepB/blink), frame names')
    A('`<id>_<dir>_<n>`, anims `<id>_walk_<dir>`, `<id>_idle_<dir>`. `sprites` lists name, cell and origin per id.')
    A('Townsfolk ids (cast names from W1-content):')
    A('')
    A('| id | who | look |')
    A('|---|---|---|')
    looks = {
        'npc_elder': 'green hooded robe, long white beard, staff with green orb',
        'npc_tess': 'brown ponytail, teal tunic, courier satchel',
        'npc_baker': 'stout, baker cap, white apron, short beard',
        'npc_ferry': 'blonde, long blue coat-dress, cream scarf',
        'npc_innkeeper': 'stout, dark full beard, red shirt, apron, mug',
        'npc_shopkeeper': 'turban, mustache, mustard robe with blue trim',
        'npc_smith': 'stout, about 70, iron-grey hair and beard, leather apron, hammer',
        'npc_child_a': 'small boy, red tunic',
        'npc_child_b': 'small girl, blonde ponytail, pink top',
        'npc_guard': 'helmet, blue tunic, spear',
        'npc_old_woman': 'grey bun, plum shawl, brown dress',
        'npc_farmer': 'straw hat, green shirt',
        'npc_scholar': 'navy bun, glasses, blue robe, book',
        'npc_parent': 'auburn hair, green dress, cream apron',
        'npc_bellkeeper': 'balding, grey beard, chapel-purple robe, lantern',
    }
    for k in npc_ids:
        A('| `%s` | %s | %s |' % (k, npcs['sprites'][k].get('name', ''), looks.get(k, '')))
    A('')
    A('Animals (16x16, face LEFT, flip for right): ' + ', '.join('`%s`' % a for a in animal_ids) +
      ' with frames `<id>_{sit_0,sit_1,walk_0}` (cat, dog) or `<id>_{stand_0,peck_0|stand_1,walk_0}`')
    A('(chicken, duck); anims `<id>_idle`, `<id>_walk`. `npc_dough` (Oren\'s runaway starter): `npc_dough_0/1`,')
    A('anim `npc_dough_wobble`.')
    A('')
    A('## props.png / .json')
    A('`objects.<id>`: `frame [x,y,w,h]`, `anchor [px,py]` (bottom-centre of the footprint inside the frame),')
    A('`footprint [wTiles,hTiles]`, `solid`, `overheadY` (frame rows above it draw over actors, 0 = none), optional')
    A('`frames`/`frameNames` (state alternates), `passable` tiles, `breaksTo`. Placement: ' + props['notes'])
    A('')
    A(ids_line(props['objects'].keys()))
    A('')
    A('Chests: `chest_wood|iron|gold` with frames [closed, open]. `lamp_post` frames [unlit, lit]; `lamp_glow` is an')
    A('additive glow disc. `prop_letter` frames [plain, glint]. `pot` breaks to `pot_broken`.')
    A('')
    A('## enemies_battle.png / .json, bosses_battle.png / .json  (face RIGHT, origin = bottom-centre)')
    A('enemies_battle: ' + ', '.join('`%s`' % k for k in eb['frames']) + '.')
    A('bosses_battle: ' + ', '.join('`%s`' % k for k in bb['frames']) + ' (anim `lost_page_flutter`).')
    A('`enemies_battle.json.external` maps the boss-sheet ids so battle code can look up any enemy id.')
    A('Recolours: page_wraith and bookmite are parchment/ink gradient maps, briar_wolf brown fur + green briar,')
    A('ink_wraith ink-violet. Idle motion, hit flash and death dissolve are procedural (DESIGN 6.3).')
    A('')
    A('## enemies_field.png / .json  (visible map enemies, face LEFT)')
    A('`sprites.<id>.size/origin`; frames `<id>_0`, `<id>_1`; anim `<id>_idle`. Ids: ' +
      ', '.join('`%s`' % k for k in ef['sprites']) + '.')
    A('')
    A('## portraits.png / .json')
    A('`portraits.<id>` -> `{"48": frame, "32": frame}`; both sizes include a 1 px bevel frame and a dark backdrop.')
    A('')
    A('| id | source |')
    A('|---|---|')
    for k, v in po['sources'].items():
        note = ' (unassigned, for later episodes)' if k in po.get('unassigned', []) else ''
        A('| `%s` | %s%s |' % (k, v, note))
    A('')
    A('Garrick and Pip are recoloured from the NPC paintings (iron-grey hair, chapel purple). No sources exist yet for')
    A('Oren, Edda, Holt, Cobb, Quill, Penny: the UI should fall back to no portrait for them.')
    A('')
    A('## misc.png / .json')
    A('`shadow_small|medium|large|huge` (palette shadow_overlay at its alpha), `sparkle_0..2`, `dust_0..2`')
    A('(anims `sparkle`, `dust`, play once). origin = centre.')
    A('')
    A('## Colours outside the master palette')
    A('Per-sprite extras kept because no ramp carries them (DESIGN 6.1 allows skin/hair/eye extras):')
    for hx, who in sorted(extras.items()):
        A('- `%s` used by %s' % (hx, ', '.join(sorted(who))))
    A('')
    A('Painted conversions (props, enemies, bosses, portraits) quantize to a small per-sprite palette and snap every')
    A('colour within a small OKLab distance of a master colour onto it; the rest stay as painted.')
    A('')
    with open(os.path.join(DST, 'README.md'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(L))
