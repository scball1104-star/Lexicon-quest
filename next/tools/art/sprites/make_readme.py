"""Writes next/assets/sprites/README.md from the generated atlases (ids stay in sync with the build)."""
import os, json
from pix import DST


def load(n):
    with open(os.path.join(DST, n + '.json'), encoding='utf-8') as f:
        return json.load(f)


def ids_line(ids, per=6):
    ids = list(ids)
    rows = []
    for i in range(0, len(ids), per):
        rows.append(', '.join('`%s`' % x for x in ids[i:i + per]))
    return '\n'.join('  ' + r for r in rows)


