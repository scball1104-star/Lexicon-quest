"""Timeline head icons for the Episode 7 foes -> assets/ui/ep7_heads.png / .json (E7-sprites).

Same format as build_heads.py (12x12 including a 1 px #14101e frame around a 10x10 head on #251d34, origin [0, 0], names
head_<id>, enemies face right). Merged into `heads` by the pack loader (atlas id ep7_heads). The foes with a field sprite
are 10x10 crops of its frame 0 (flipped to face right, as build_heads.py does for Episodes 1 to 6); the White Phantom,
the Closed Gate and the Lost Letter are drawn at icon size so each reads as its own being in the timeline. The frost on a
party member's head (Rime, Frozen) is drawn by the battle scene, never baked in (plan 6.3 and 9.2).
"""
