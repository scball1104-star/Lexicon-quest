"""Timeline head icons for the three Expansion 1 foes -> assets/ui/x1_heads.png / .json (X1-sprites).

Same format as build_heads.py (12x12 including a 1 px #14101e frame around a 10x10 head on #251d34, origin [0, 0], names
head_<id>, enemies face right). Merged into `heads` by the pack loader (atlas id x1_heads). Hand-drawn at icon size,
not cropped: the shade's hood with its two candle-green lamps, the Reeve's helm with the crook's hook, and the
Millstone Golem as a grindstone (axle hole, furrows, a crack), so the three read as different beings in a timeline.
"""
