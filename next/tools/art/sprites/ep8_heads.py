ORDER = ['index_hound', 'margin_imp', 'paper_crane', 'gnawing_bookworm', 'catalog_wraith', 'inkbound_librarian', 'struck_page',
         'unnamed_sentry', 'eraser', 'truth_grief', 'truth_change']


def build(field_frames, write=True):
    heads = {}
    for k, (x, y) in CROPS.items():
        s = field_frames[k][0]
        crop = blank(10, 10)
        sub = s[y:y + 10, x:x + 10]
        crop[:sub.shape[0], :sub.shape[1]] = sub
        heads[k] = BH.framed(crop[:, ::-1].copy())
    for k, (rows, leg) in GRIDS.items():
        assert all(len(r) == 10 for r in rows) and len(rows) == 10, k
        heads[k] = BH.framed(parse_grid(rows, P.resolve(leg, 'head_' + k), w=10, h=10))
    sheet = blank(len(ORDER) * 12, 12)
    frames = {}
    for i, k in enumerate(ORDER):
        sheet[:, i * 12:(i + 1) * 12] = heads[k]
        frames['head_' + k] = [i * 12, 0, 12, 12]
    meta = {'image': 'ep8_heads.png', 'cell': [12, 12], 'origin': [0, 0], 'frames': frames,
            'frameColor': BH.FRAME, 'backColor': BH.BACK, 'inner': [1, 1, 10, 10],
            'side': {k: 'enemy' for k in ORDER},
            'notes': 'Episode 8 pack atlas, merged into heads. Same 12x12 format as heads.json, enemies face right. The Unnamed '
                     'Sentry has one head (the blank faceplate) for both looks; the Eraser one head (the empty white face '
                     'under the hood) for all four (eraser, eraser_truths, eraser_remembers, eraser_silence). The smudge on a '
                     'party head (a rubbed-out row) is drawn by the scene, not baked. Generated by '
                     'tools/art/sprites/ep8_heads.py.'}
    if write:
        import anim_atlas as AA
        AA.save_indexed(sheet, os.path.join(BH.UI, 'ep8_heads.png'))
        write_json(os.path.join(BH.UI, 'ep8_heads.json'), meta)
    os.makedirs(os.path.join(OUT, 'ep8'), exist_ok=True)
    for s in (1, 8):
        contact([(k if s > 1 else '', heads[k]) for k in ORDER], os.path.join(OUT, 'ep8', f'ep8_heads_{s}x.png'), scale=s,
                cols=6, title='Episode 8 timeline heads at %dx' % s if s > 1 else None, bg=(30, 46, 110), label=s > 1)
    return meta, heads


