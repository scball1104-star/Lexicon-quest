"""Timeline head icons for the Episode 8 foes -> assets/ui/ep8_heads.png / .json (E8-sprites).

Same format as build_heads.py (12x12 including a 1 px #14101e frame around a 10x10 head on #251d34, origin [0, 0], names
head_<id>, enemies face right). Merged into `heads` by the pack loader (atlas id ep8_heads). The foes with a field sprite
are 10x10 crops of its frame 0 (flipped to face right, as build_heads.py does for Episodes 1 to 7); the Eraser, Grief and
Change are drawn at icon size so each reads as its own being in the timeline. The Unnamed Sentry has one head (the blank
faceplate) for both of its looks and the Eraser one (the empty white face under the hood) for all four. The smudge on a
party member's head (a rubbed-out row) is drawn by the battle scene, never baked in (plan 6.3 and 9.2). No NPC fights or
speaks in an Episode 8 battle, so there are no NPC heads.
"""
