SPARK_PAL = {'w': 'gold:4', 'W': 'gold:5', 'y': 'magic_cyan:3'}
DUST_PAL = {'u': 'stone_warm:3', 'v': 'stone_warm:4', 'w': 'stone_warm:5'}


def build():
    items = [('shadow_small', ellipse_shadow(12, 4)), ('shadow_medium', ellipse_shadow(18, 6)),
             ('shadow_large', ellipse_shadow(28, 8)), ('shadow_huge', ellipse_shadow(48, 12))]
    sl = P.resolve(SPARK_PAL, 'sparkle')
    dl = P.resolve(DUST_PAL, 'dust')
    for i, g in enumerate(SPARKLE):
        items.append((f'sparkle_{i}', parse_grid(grid_from_text(g), sl, w=9, h=9)))
    for i, g in enumerate(DUST):
        items.append((f'dust_{i}', parse_grid(grid_from_text(g), dl, w=12, h=12)))
    sh = Shelf(64, pad=1)
    for n, im in items:
        sh.add(n, im)
    sheet, rects = sh.render()
    save_png(sheet, os.path.join(DST, 'misc.png'))
    role = P.master()['roles']['shadow_overlay']
    meta = {'image': 'misc.png', 'frames': rects,
            'origin': {n: [r[2] // 2, r[3] // 2] for n, r in rects.items()},
            'anims': {'sparkle': {'frames': ['sparkle_0', 'sparkle_1', 'sparkle_2'], 'fps': 12, 'loop': False},
                      'dust': {'frames': ['dust_0', 'dust_1', 'dust_2'], 'fps': 12, 'loop': False}},
            'notes': ('Shadows are the palette shadow_overlay colour at alpha %.2f (rim %.2f); draw them centred under '
                      'an actor\'s feet before the actor: small = 16px critters, medium = party/NPCs, large = 24-32px '
                      'enemies, huge = bosses. sparkle/dust: play once, origin = centre.') % (role['alpha'], role['alpha'] * 0.6)}
    write_json(os.path.join(DST, 'misc.json'), meta)
    contact(items, os.path.join(OUT, 'misc_8x.png'), scale=8, cols=6, title='misc at 8x', bg=(120, 150, 90))
    return meta


if __name__ == '__main__':
    build()
