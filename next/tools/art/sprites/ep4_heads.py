ORDER = ['flood_hound', 'lockjaw_crab', 'ink_bloom', 'drowned_watch', 'gutter_phantom', 'blank_decree',
         'waterlogged_sentinel', 'barrister', 'barrister_witness', 'paper_regent', 'writ_silence', 'writ_oblivion']


def build(field_frames, write=True):
    heads = {}
    for k, (x, y) in CROPS.items():
        s = field_frames[k][0]
        crop = blank(10, 10)
        sub = s[y:y + 10, x:x + 10]
        crop[:sub.shape[0], :sub.shape[1]] = sub
        heads[k] = BH.framed(crop[:, ::-1].copy())
    for k, (rows, leg) in GRIDS.items():
        assert all(len(r) == 10 for r in rows) and len(rows) == 10, k
        heads[k] = BH.framed(parse_grid(rows, P.resolve(leg, 'head_' + k), w=10, h=10))
    sheet = blank(len(ORDER) * 12, 12)
    frames = {}
    for i, k in enumerate(ORDER):
        sheet[:, i * 12:(i + 1) * 12] = heads[k]
        frames['head_' + k] = [i * 12, 0, 12, 12]
    meta = {'image': 'ep4_heads.png', 'cell': [12, 12], 'origin': [0, 0], 'frames': frames,
            'frameColor': BH.FRAME, 'backColor': BH.BACK, 'inner': [1, 1, 10, 10],
            'side': {k: 'enemy' for k in ORDER},
            'notes': 'Episode 4 pack atlas, merged into heads. Same 12x12 format as heads.json, enemies face right. The Paper Regent has one head for all three looks. Generated by tools/art/sprites/ep4_heads.py.'}
    if write:
        save_png(sheet, os.path.join(BH.UI, 'ep4_heads.png'))
        write_json(os.path.join(BH.UI, 'ep4_heads.json'), meta)
        os.makedirs(os.path.join(OUT, 'ep4'), exist_ok=True)
        contact([(k, heads[k]) for k in ORDER], os.path.join(OUT, 'ep4', 'ep4_heads_8x.png'), scale=8, cols=6,
                title='Episode 4 timeline heads at 8x', bg=(30, 46, 110))
    return meta, heads
