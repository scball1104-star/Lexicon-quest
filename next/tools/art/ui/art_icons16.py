def icons16():
    out = {}
    for k, (art, mats) in ART.items():
        a = draw(art, **mats)
        c = blank(16, 16)
        paste(c, a, (16 - a.shape[1]) // 2, (16 - a.shape[0]) // 2)
        out[k] = c
    return out


def sprites():
    return [(f'icon16_{k}', v, None) for k, v in icons16().items()]


