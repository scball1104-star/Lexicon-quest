def mini_badge(name):
    """8x8 status badge for the battle HUD row: rim, 1 px top highlight, 5x5 white symbol at (2, 2)."""
    r = STATUS_RAMPS[name]
    n = len(r)
    rim, fill, hi = r[0], r[min(n - 1, 2)], r[min(n - 1, 3)]
    b = blank(8, 8)
    for y in range(8):
        for x in range(8):
            if (x in (0, 7)) and (y in (0, 7)):
                continue
            edge = x in (0, 7) or y in (0, 7)
            b[y, x] = hexc(rim if edge else fill)
    for x in range(1, 7):
        b[1, x] = hexc(hi)
    for y, row in enumerate(MINI[name]):
        for x, ch in enumerate(row):
            if ch == 'W':
                b[2 + y, 1 + x + (1 if False else 0)] = hexc(P.WHITE)
    # symbol shadow pixel to the right/bottom inside the tile for separation
    return b


