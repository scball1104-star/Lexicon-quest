def _ramp_slice(r, lo, hi):
    """pick 3 badge colors from a ramp: dark edge, mid border, fill."""
    return r


def badge(name, size=12):
    r = STATUS_RAMPS[name]
    n = len(r)
    # dark rim = ramp[0], border = ramp[mid-ish], fill = ramp[mid]
    rim, border, fill = r[0], r[min(n - 1, 3)], r[min(n - 1, 2)]
    if name in ('stun',):
        rim, border, fill = r[0], r[3], r[2]
    if name == 'blind':
        rim, border, fill = r[0], r[3], r[2]
    if size == 12:
        b = blank(12, 12)
        cm = {'1': rim, '2': border, '3': fill}
        for y, row in enumerate(BADGE):
            for x, ch in enumerate(row):
                if ch in cm:
                    b[y, x] = hexc(cm[ch])
        # soft top highlight
        for x in range(2, 10):
            b[2, x] = hexc(r[min(n - 1, 3)])
        sym = draw(SYM[name], extra={'W': P.WHITE, '+': P.WHITE}, outline=False)
        # symbol drop shadow in rim color, then symbol
        m = sym[..., 3] > 0
        sh = np.zeros_like(sym)
        sh[m] = hexc(rim)
        paste(b, sh, 1, 1)
        symc = sym.copy()
        symc[m] = hexc(P.WHITE)
        # '+' marks (bright core) in cream gold for warmth
        paste(b, symc, 0, 0)
        if name in ('blind', 'silence'):
            # red slash across
            for i in range(8):
                x, y = 2 + i, 9 - i
                b[y, x] = hexc(P.RED[4])
                if i < 7:
                    b[y, x + 1] = hexc(P.RED[2])
        return b
    raise ValueError


